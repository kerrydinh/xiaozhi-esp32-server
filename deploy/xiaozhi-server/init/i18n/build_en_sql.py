#!/usr/bin/env python3
"""Generate en.sql from en.json.

en.json holds the English translations of console data seeded by
xiaozhi-esp32-server's database migrations:
  rows:   [{"t": table, "c": column, "id": row id, "zh": original, "en": text}]
  labels: [{"zh": original, "en": text}]   # form-field labels in ai_model_provider.fields

Every UPDATE only fires while the cell still holds the exact original Chinese
text, so re-running is harmless and edits made in the console are never
overwritten. Usage: python3 build_en_sql.py  (writes en.sql next to this file)
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
HAN = re.compile(r"[一-鿿]")
# Only display columns, with their max length in characters (TEXT = 65535 bytes).
# Functional values (placeholders, prompts, TTS languages) stay untouched.
ALLOWED = {
    ("sys_dict_type", "dict_name"): 255,
    ("sys_dict_type", "remark"): 255,
    ("sys_dict_data", "dict_label"): 255,
    ("sys_dict_data", "remark"): 255,
    ("sys_params", "remark"): 200,
    ("ai_model_provider", "name"): 50,
    ("ai_model_config", "model_name"): 50,
    ("ai_model_config", "remark"): 65535 // 4,
    ("ai_agent_template", "agent_name"): 64,
}


def q(value: str) -> str:
    """MySQL string literal (default sql_mode, backslash escapes enabled)."""
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def main() -> None:
    data = json.loads((HERE / "en.json").read_text(encoding="utf-8"))
    out = [
        "-- Generated by build_en_sql.py from en.json. Do not edit by hand.",
        "SET NAMES utf8mb4;",
    ]

    for row in data["rows"]:
        table, column = row["t"], row["c"]
        if (table, column) not in ALLOWED:
            raise SystemExit(f"column not allowed: {table}.{column}")
        if len(row["en"]) > ALLOWED[(table, column)]:
            raise SystemExit(f"too long for {table}.{column} ({ALLOWED[(table, column)]}): {row['en']}")
        if not row["en"].strip() or row["en"] == row["zh"]:
            continue
        out.append(
            f"UPDATE `{table}` SET `{column}` = {q(row['en'])} "
            f"WHERE id = {q(str(row['id']))} AND `{column}` = {q(row['zh'])};"
        )

    for label in data["labels"]:
        zh, en = label["zh"], label["en"]
        if HAN.search(en):
            raise SystemExit(f"label still contains Chinese: {en}")
        # MySQL serialises JSON as "key": "value"; json.dumps applies JSON escaping
        old = f'"label": {json.dumps(zh, ensure_ascii=False)}'
        new = f'"label": {json.dumps(en, ensure_ascii=False)}'
        like = old.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
        out.append(
            f"UPDATE `ai_model_provider` SET `fields` = REPLACE(`fields`, {q(old)}, {q(new)}) "
            f"WHERE `fields` LIKE {q('%' + like + '%')};"
        )

    (HERE / "en.sql").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(out) - 2} statements to {HERE / 'en.sql'}")


if __name__ == "__main__":
    main()
