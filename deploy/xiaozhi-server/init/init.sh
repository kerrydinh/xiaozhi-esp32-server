#!/usr/bin/env bash
# One-shot provisioning for the XiaoZhi stack. Runs after the manager API is
# healthy and before the voice server starts. Every step is idempotent.
set -euo pipefail

log() { echo "[init] $*"; }
die() { echo "[init] ERROR: $*" >&2; exit 1; }

export MYSQL_PWD="${MYSQL_ROOT_PASSWORD:?MYSQL_ROOT_PASSWORD is not set}"
sql() { mysql -h db -uroot --default-character-set=utf8mb4 -N -B xiaozhi_esp32_server "$@"; }
# Quote a value as a SQL string literal
sqlq() { local s=${1//\\/\\\\}; s=${s//\'/\'\'}; printf "'%s'" "$s"; }

API_URL="http://web:8002/xiaozhi"
CONFIG_FILE=/data/.config.yaml
MODEL_DIR=/models/SenseVoiceSmall
MODEL_FILE=$MODEL_DIR/model.pt
MODEL_SIZE=936291369
MODEL_SHA256=833ca2dcfdf8ec91bd4f31cfac36d6124e0c459074d5e909aec9cabe6204a3ea

# --- 1. SenseVoiceSmall ASR model (used by the default FunASR provider) -----
mkdir -p "$MODEL_DIR"
if [ "${SENSEVOICE_DOWNLOAD:-true}" = "true" ]; then
  if [ -f "$MODEL_FILE" ] && [ "$(stat -c %s "$MODEL_FILE")" = "$MODEL_SIZE" ]; then
    log "SenseVoiceSmall model present"
  else
    log "Downloading SenseVoiceSmall model (~900 MB) from $SENSEVOICE_URL"
    curl -fL --retry 5 --retry-delay 5 -C - -o "$MODEL_FILE.part" "$SENSEVOICE_URL"
    echo "$MODEL_SHA256  $MODEL_FILE.part" | sha256sum -c --quiet - || {
      rm -f "$MODEL_FILE.part"
      die "model checksum mismatch; download removed, restart to retry"
    }
    mv -f "$MODEL_FILE.part" "$MODEL_FILE"
    log "SenseVoiceSmall model downloaded"
  fi
elif [ ! -s "$MODEL_FILE" ]; then
  log "SENSEVOICE_DOWNLOAD=false: no local model; switch the agent's ASR away from FunASR in the console"
fi

# --- 2. Wait for the manager API (liquibase migrations + server.secret) ------
for i in $(seq 1 60); do
  curl -fsS "$API_URL/user/pub-config" >/dev/null 2>&1 && break
  [ "$i" = 60 ] && die "manager API at $API_URL did not come up"
  sleep 5
done

SECRET=$(sql -e "SELECT param_value FROM sys_params WHERE param_code='server.secret'")
case "$SECRET" in ""|null) die "server.secret has not been generated yet" ;; esac

# --- 3. Voice server config (data/.config.yaml) ------------------------------
if [ -n "${PUBLIC_HOST:-}" ]; then
  VISION_URL="http://$PUBLIC_HOST:$HTTP_PORT/mcp/vision/explain"
else
  VISION_URL="http://你的ip或者域名:端口号/mcp/vision/explain"   # upstream placeholder = unset
fi

if [ ! -f "$CONFIG_FILE" ]; then
  log "Writing $CONFIG_FILE"
  cat > "$CONFIG_FILE" <<EOF
# Generated by init.sh. Only manager-api.secret and server.vision_explain are
# kept in sync on each start; other edits are preserved.
server:
  ip: 0.0.0.0
  port: 8000
  http_port: 8003
  vision_explain: $VISION_URL
manager-api:
  url: $API_URL
  secret: $SECRET
prompt_template: agent-base-prompt.txt
EOF
else
  sed -i -E "s|^(  secret:).*|\1 $SECRET|; s|^(  vision_explain:).*|\1 $VISION_URL|" "$CONFIG_FILE"
  log "Updated secret and vision_explain in $CONFIG_FILE"
fi

# Extra providers; the server copies them into its source tree on start
mkdir -p /data/custom
cp -rf /init/custom/. /data/custom/

# --- 4. Device-facing URLs, from .env --------------------------------------
before=$(sql -e "CHECKSUM TABLE sys_params, sys_dict_type, sys_dict_data, ai_model_provider, ai_model_config, ai_agent_template, ai_tts_voice" | cut -f2 | tr '\n' ' ')

set_param() {
  sql -e "UPDATE sys_params SET param_value=$(sqlq "$2") WHERE param_code=$(sqlq "$1") AND NOT param_value <=> $(sqlq "$2")"
}
if [ -n "${PUBLIC_HOST:-}" ]; then
  set_param server.websocket "ws://$PUBLIC_HOST:$WS_PORT/xiaozhi/v1/"
  set_param server.ota "http://$PUBLIC_HOST:$WEB_PORT/xiaozhi/ota/"
  set_param server.fronted_url "http://$PUBLIC_HOST:$WEB_PORT"
  log "Device URLs: ws://$PUBLIC_HOST:$WS_PORT/xiaozhi/v1/ , OTA http://$PUBLIC_HOST:$WEB_PORT/xiaozhi/ota/"
else
  log "PUBLIC_HOST is empty: set server.websocket and server.ota in the console yourself"
fi

# --- 5. English console data (names, labels, help texts) -------------------
if [ "${CONSOLE_DATA_LANGUAGE:-en}" = "en" ]; then
  sql < /init/i18n/en.sql
  log "Applied English console data"
fi

# --- 6. Stack additions: OpenAI-compatible ASR provider, extra voices -------
sql < /init/sql/custom.sql

# Ready-made ASR entry for an Ollama/OpenAI-compatible endpoint. Created once;
# afterwards edit it in the console (Model Config > Speech Recognition).
if [ -n "${OLLAMA_ASR_URL:-}" ]; then
  asr_config=$(printf '{"type": "openai_compat", "base_url": "%s", "model_name": "%s", "api_key": "ollama", "timeout": 60, "output_dir": "tmp/"}' \
    "$OLLAMA_ASR_URL" "${OLLAMA_ASR_MODEL:-}")
  sql -e "INSERT IGNORE INTO ai_model_config (id, model_type, model_code, model_name, is_default, is_enabled, config_json, remark, sort, creator, create_date, updater, update_date)
          VALUES ('ASR_OllamaQwen3', 'ASR', 'OllamaQwen3ASR', 'Ollama Qwen3-ASR', 0, 1, $(sqlq "$asr_config"),
                  'Speech recognition through an OpenAI-compatible /v1/audio/transcriptions endpoint (Ollama). Created from OLLAMA_ASR_URL in .env; edit here afterwards.',
                  0, 1, NOW(), 1, NOW())"
  log "ASR model 'Ollama Qwen3-ASR' available ($OLLAMA_ASR_URL)"
fi

# Ready-made TTS entry for a VieNeu-TTS speech API (OpenAI-compatible), with
# its preset voices. Created once; edit it in the console afterwards.
if [ -n "${VIENEU_TTS_URL:-}" ]; then
  tts_config=$(printf '{"type": "openai", "api_url": "%s", "api_key": "%s", "model": "vieneu-v3-turbo", "voice": "Hải Đăng", "speed": 1, "output_dir": "tmp/"}' \
    "$VIENEU_TTS_URL" "${VIENEU_TTS_API_KEY:-}")
  sql -e "INSERT IGNORE INTO ai_model_config (id, model_type, model_code, model_name, is_default, is_enabled, config_json, remark, sort, creator, create_date, updater, update_date)
          VALUES ('TTS_VieNeuTTS', 'TTS', 'VieNeuTTS', 'VieNeu-TTS (Vietnamese)', 0, 1, $(sqlq "$tts_config"),
                  'Vietnamese speech from a VieNeu-TTS server (OpenAI-compatible /v1/audio/speech). Created from VIENEU_TTS_URL in .env; edit here afterwards.',
                  0, 1, NOW(), 1, NOW())"
  sql < /init/sql/vieneu.sql
  log "TTS model 'VieNeu-TTS (Vietnamese)' available ($VIENEU_TTS_URL)"
fi

# --- 7. Drop the API's Redis cache if the database changed -----------------
after=$(sql -e "CHECKSUM TABLE sys_params, sys_dict_type, sys_dict_data, ai_model_provider, ai_model_config, ai_agent_template, ai_tts_voice" | cut -f2 | tr '\n' ' ')
if [ "$before" != "$after" ]; then
  reply="no reply"
  exec 3<>/dev/tcp/redis/6379
  printf '*1\r\n$7\r\nFLUSHDB\r\n' >&3
  IFS= read -r -t 5 reply <&3 || true
  exec 3>&-
  log "Database changed; cleared API cache (${reply%$'\r'})"
fi

log "Done"
